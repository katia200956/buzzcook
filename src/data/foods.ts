export const foodById = (id: string) => foods.find((x) => x.id === id);

// Matches every word of the query against the name or category, so "сир 5" finds "сир кисломолочний 5%".
// `mine` (scanned or typed-in products) come first.
export const searchFoods = (q: string, mine: Food[] = []) => {
  const all = [...mine, ...foods];
  const words = q.toLowerCase().trim().split(/\s+/).filter(Boolean);
  if (!words.length) return all;
  return all.filter((x) => words.every((w) => x.name.toLowerCase().includes(w) || x.cat.includes(w)));
};
